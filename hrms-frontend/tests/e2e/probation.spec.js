import { test, expect } from '@playwright/test'
import { setup, criteria } from './probation-fixture.js'

test('role-aware probation and reviewer navigation', async ({ page }) => {
  await setup(page, 'EMPLOYEE', 'DRAFT')
  await page.goto('/my-probation')
  await expect(page.getByRole('link', { name: 'My Probation', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Assigned evaluations', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Users', exact: true })).toHaveCount(0)
})
test('HR creates a draft with inline validation and sends it to manager', async ({ page }) => {
  const api = await setup(page)
  await page.goto('/probation/assessments/new')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('alert')).toBeFocused()
  await expect(page.locator('#employeeId')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Employee', { exact: false }).selectOption('1')
  await page.getByLabel('Probation start date').fill('2026-01-01')
  await page.getByLabel('Probation end date').fill('2026-06-30')
  await page.getByLabel('Review due date').fill('2026-06-15')
  await page.getByLabel('Assigned manager').selectOption('20')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Probation assessment #42' })).toBeVisible()
  await page.getByRole('button', { name: 'Send to manager' }).click()
  await expect(page.getByText('Pending manager evaluation', { exact: true })).toBeVisible()
  expect(api.requests.find((r) => r.method === 'POST' && r.path.endsWith('/assessments')).body.reportingManagerUserId).toBe(20)
})
test('assigned manager saves and submits evaluation with keyboard-accessible confirmation', async ({ page }) => {
  const api = await setup(page, 'EMPLOYEE', 'PENDING_MANAGER_EVALUATION', { manager: true })
  await page.goto('/probation/assessments/42')
  for (const name of criteria) {
    await page.getByLabel(`Score: ${name}`).selectOption('4')
    await page.getByLabel(`Evidence: ${name}`).fill('Observed delivery and collaboration.')
  }
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByText('Manager evaluation in progress', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Submit evaluation', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab')
  expect(await dialog.evaluate((el) => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: 'Submit evaluation', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Submit evaluation', exact: true }).click()
  await expect(page.getByText('Pending HR review', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Publish final decision' })).toHaveCount(0)
  expect(api.requests.filter((r) => r.path.endsWith('/evaluation') && r.method === 'PUT').length).toBe(2)
})
