test('responsive list and evaluation stay usable in both themes', async ({ page }, testInfo) => {
  await setup(page, 'EMPLOYEE', 'PENDING_MANAGER_EVALUATION', { manager: true })
  for (const width of [375, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/manager-evaluations')
    await expect(page.getByRole('heading', { name: 'Assigned evaluations' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'View assessment 42' })).toHaveCount(0) // Navigation remains a semantic link.
    await expect(page.getByRole('link', { name: 'View assessment 42' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`list-${width}.png`), fullPage: true })
    await page.goto('/probation/assessments/42')
    await expect(page.getByLabel('Score: Work quality')).toBeVisible()
    await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`evaluation-dark-${width}.png`), fullPage: true })
  }
})
