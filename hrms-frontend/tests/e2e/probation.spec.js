test('ADMIN validates extension reason/date and publishes a final outcome', async ({ page }) => {
  const api = await setup(page, 'ADMIN', 'PENDING_ADMIN_APPROVAL')
  await page.goto('/probation/assessments/42')
  await page.getByLabel('Final decision').selectOption('EXTENDED')
  await page.getByRole('button', { name: 'Publish final decision' }).click()
  await expect(page.getByRole('alert')).toBeFocused()
  await page.getByLabel('Approved revised end date').fill('2026-09-30')
  await page.getByLabel('Internal decision remarks').fill('Allow further development time.')
  await page.getByLabel('Approved comments for employee').fill('Your probation has been extended with mentoring support.')
  await page.getByRole('button', { name: 'Publish final decision' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Publish decision' }).click()
  await expect(page.getByRole('heading', { name: 'Probation assessment #42' })).toBeVisible()
  await expect(page.getByText('Your probation has been extended with mentoring support.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Publish final decision' })).toHaveCount(0)
  expect(api.requests.find((r) => r.path.endsWith('/decision')).body.revisedEndDate).toBe('2026-09-30')
})
