CREATE TABLE probation_schema.probation_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL CHECK (employee_id > 0),
    employee_name VARCHAR(255) NOT NULL,
    employee_department VARCHAR(255),
    probation_start_date DATE NOT NULL,
    probation_end_date DATE NOT NULL,
    review_due_date DATE NOT NULL,
    reporting_manager_user_id BIGINT NOT NULL CHECK (reporting_manager_user_id > 0),
    manager_employee_id BIGINT NOT NULL,
    manager_name VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    criteria_version VARCHAR(30) NOT NULL,
    initial_remarks VARCHAR(4000),
    strengths VARCHAR(4000),
    areas_for_improvement VARCHAR(4000),
    development_recommendations VARCHAR(4000),
    recommendation VARCHAR(30),
    overall_score NUMERIC(3,2),
    hr_review_remarks VARCHAR(4000),
    final_decision VARCHAR(30),
    decision_remarks VARCHAR(4000),
    published_comments VARCHAR(4000),
    revised_end_date DATE,
    decision_date TIMESTAMP WITH TIME ZONE,
    decided_by BIGINT,
    published_at TIMESTAMP WITH TIME ZONE,
    previous_assessment_id BIGINT UNIQUE REFERENCES probation_schema.probation_assessments(id),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (probation_start_date <= probation_end_date),
    CHECK (review_due_date BETWEEN probation_start_date AND probation_end_date),
    CHECK (manager_employee_id <> employee_id),
    CHECK (status IN ('DRAFT','PENDING_MANAGER_EVALUATION','MANAGER_EVALUATION_IN_PROGRESS','PENDING_HR_REVIEW','RETURNED_TO_MANAGER','PENDING_ADMIN_APPROVAL','CONFIRMED','EXTENDED','NOT_CONFIRMED')),
    CHECK (recommendation IS NULL OR recommendation IN ('CONFIRMED','EXTENDED','NOT_CONFIRMED')),
    CHECK (overall_score IS NULL OR overall_score BETWEEN 1 AND 5),
    CHECK ((final_decision IS NULL AND status NOT IN ('CONFIRMED','EXTENDED','NOT_CONFIRMED') AND decision_date IS NULL AND decided_by IS NULL AND published_at IS NULL)
        OR (final_decision = status AND final_decision IN ('CONFIRMED','EXTENDED','NOT_CONFIRMED') AND decision_date IS NOT NULL AND decided_by IS NOT NULL AND published_at IS NOT NULL)),
    CHECK (final_decision IS NULL OR final_decision = 'CONFIRMED' OR coalesce(length(trim(decision_remarks)),0) > 0),
    CHECK ((final_decision = 'EXTENDED' AND revised_end_date IS NOT NULL AND revised_end_date > probation_end_date) OR (final_decision IS DISTINCT FROM 'EXTENDED' AND revised_end_date IS NULL)),
    -- Built-in range GiST operators avoid requiring the btree_gist extension.
    CONSTRAINT no_overlapping_active_probation EXCLUDE USING gist
        (int8range(employee_id, employee_id, '[]') WITH &&,
         daterange(probation_start_date, probation_end_date, '[]') WITH &&)
        WHERE (final_decision IS NULL)
);
CREATE INDEX probation_queue_idx ON probation_schema.probation_assessments(status, review_due_date, id);
CREATE INDEX probation_manager_idx ON probation_schema.probation_assessments(reporting_manager_user_id, status);
CREATE INDEX probation_employee_idx ON probation_schema.probation_assessments(employee_id, created_at DESC);

CREATE TABLE probation_schema.probation_assessment_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES probation_schema.probation_assessments(id),
    criterion_code VARCHAR(50) NOT NULL,
    criterion_name_snapshot VARCHAR(150) NOT NULL,
    weight INTEGER NOT NULL CHECK (weight > 0),
    score INTEGER CHECK (score BETWEEN 1 AND 5),
    comments VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (assessment_id, criterion_code)
);
CREATE TABLE probation_schema.probation_assessment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES probation_schema.probation_assessments(id),
    action VARCHAR(50) NOT NULL,
    previous_status VARCHAR(50),
    new_status VARCHAR(50) NOT NULL,
    performed_by BIGINT NOT NULL,
    performed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    remarks VARCHAR(4000),
    evidence_snapshot TEXT
);
CREATE INDEX probation_history_idx ON probation_schema.probation_assessment_history(assessment_id, id);

CREATE FUNCTION probation_schema.reject_history_mutation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Probation history is append-only' USING ERRCODE = '23514'; END;
$$;
CREATE TRIGGER probation_history_append_only BEFORE UPDATE OR DELETE ON probation_schema.probation_assessment_history
FOR EACH ROW EXECUTE FUNCTION probation_schema.reject_history_mutation();

CREATE FUNCTION probation_schema.protect_final_assessment() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.final_decision IS NOT NULL THEN
        RAISE EXCEPTION 'Finalized probation assessments are immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER probation_final_immutable BEFORE UPDATE OR DELETE ON probation_schema.probation_assessments
FOR EACH ROW EXECUTE FUNCTION probation_schema.protect_final_assessment();
